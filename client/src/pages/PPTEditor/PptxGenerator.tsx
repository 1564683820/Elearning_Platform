// PPT 大纲编辑器 — 根据 topic 参数生成大纲，可编辑卡片列表，支持重新生成和下载 PPTX
import { useState, useEffect, useCallback, useRef } from 'react';
import { useSearchParams } from 'react-router-dom';
import { teacherApi } from '../../api/teacher';
import {
  colors, green, radius, typography, space, cardStyle,
  IconRefresh, IconDownload, IconPpt, IconCheck,
} from '../../design-system';

// 章节数据结构
interface SectionData {
  id: string;
  title: string;
  subtopics: string[];
}

// id 计数器
let idCounter = 0;
const newId = () => `sec_${++idCounter}_${Date.now()}`;

// 课型选项（可从 API 获取，这里硬编码为低代码友好）
const LESSON_TYPES = [
  { value: 'new_lesson', label: '新授课' },
  { value: 'review', label: '复习课' },
  { value: 'exercise', label: '练习课' },
  { value: 'conversation', label: '口语课' },
] as const;

export default function PptxGenerator() {
  const [searchParams] = useSearchParams();
  const topic = searchParams.get('topic') || '';

  // 状态
  const [sections, setSections] = useState<SectionData[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [lessonType, setLessonType] = useState<string>('new_lesson');
  const [grade, setGrade] = useState('');
  const [downloading, setDownloading] = useState(false);
  const [downloadMsg, setDownloadMsg] = useState('');

  const hasAutoGenerated = useRef(false);

  // 自动生成大纲
  const generateOutline = useCallback(async () => {
    if (!topic.trim()) {
      setError('缺少 topic 参数');
      return;
    }
    setLoading(true);
    setError('');
    try {
      const data = await teacherApi.ppt.generateOutline({
        title: topic.trim(),
        lesson_type: lessonType,
        grade: grade || undefined,
      });
      const raw = (data as any)?.sections || [];
      setSections(raw.map((s: any) => ({
        id: newId(),
        title: s.title || '',
        subtopics: (s.subtopics || []).map((st: string) => st),
      })));
    } catch (e: any) {
      setError(e?.message || '大纲生成失败，请重试');
    } finally {
      setLoading(false);
    }
  }, [topic, lessonType, grade]);

  // 页面加载时自动生成
  useEffect(() => {
    if (hasAutoGenerated.current) return;
    hasAutoGenerated.current = true;
    if (topic.trim()) {
      generateOutline();
    }
  }, [topic, generateOutline]);

  // ==================== 大纲编辑 ====================

  const updateSectionTitle = (id: string, val: string) => {
    setSections(prev => prev.map(s => s.id === id ? { ...s, title: val } : s));
  };

  const updateSubtopic = (secId: string, idx: number, val: string) => {
    setSections(prev => prev.map(s =>
      s.id === secId
        ? { ...s, subtopics: s.subtopics.map((st, i) => i === idx ? val : st) }
        : s
    ));
  };

  const addSubtopic = (secId: string) => {
    setSections(prev => prev.map(s =>
      s.id === secId ? { ...s, subtopics: [...s.subtopics, ''] } : s
    ));
  };

  const removeSubtopic = (secId: string, idx: number) => {
    setSections(prev => prev.map(s =>
      s.id === secId ? { ...s, subtopics: s.subtopics.filter((_, i) => i !== idx) } : s
    ));
  };

  const addSection = () => {
    setSections(prev => [...prev, { id: newId(), title: '', subtopics: [''] }]);
  };

  const removeSection = (id: string) => {
    setSections(prev => prev.filter(s => s.id !== id));
  };

  // ==================== 导出 HTML 课件 ====================

  const handleExportHtml = async () => {
    const validSections = sections.filter(s => s.title.trim());
    if (validSections.length === 0) {
      setError('请至少填写一个章节标题');
      return;
    }
    setDownloading(true);
    setDownloadMsg('正在生成 PPT...');
    setError('');
    try {
      // Step 1: 基于大纲生成完整 PPT（含 HTML 内容）
      const result = await teacherApi.ppt.generateFromOutline({
        title: topic.trim() || '未命名课件',
        lesson_type: lessonType,
        grade: grade || undefined,
        sections: validSections.map(s => ({
          title: s.title.trim(),
          subtopics: s.subtopics.filter(st => st.trim()),
        })),
        theme_name: 'classic',
      });
      const pptId = result?.id;
      if (!pptId) throw new Error('PPT 生成失败');

      setDownloadMsg('正在导出 HTML...');

      // Step 2: 导出 HTML 课件
      const exportResult = await teacherApi.ppt.export(pptId);
      if (exportResult?.html_content) {
        const blob = new Blob([exportResult.html_content], { type: 'text/html;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${topic.trim() || '课件'}.html`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      }
      setDownloadMsg('');
    } catch (e: any) {
      setError('导出失败: ' + (e?.message || '未知错误'));
    } finally {
      setDownloading(false);
    }
  };

  // ==================== 渲染 ====================

  const XS = 8;
  const hasSections = sections.length > 0;

  return (
    <div style={{ maxWidth: 860, margin: '0 auto', padding: `${space.section}px 0` }}>
      {/* 页面标题 */}
      <div style={{ marginBottom: space.lg }}>
        <h1 style={{
          margin: 0, ...typography['display-lg'], color: colors['text-primary'],
        }}>
          课件大纲编辑
        </h1>
        <p style={{
          margin: `${XS}px 0 0`, ...typography['body-sm'], color: colors['text-secondary'],
        }}>
          主题：{topic || '（未指定）'} · AI 已自动生成大纲，你可以自由编辑
        </p>
      </div>

      {/* 参数区：课型 + 年级 */}
      <div style={{
        ...cardStyle, marginBottom: space.md, padding: space.md,
        display: 'flex', gap: space.md, flexWrap: 'wrap', alignItems: 'flex-end',
      }}>
        <div style={{ flex: '1 1 200px' }}>
          <label style={{
            display: 'block', ...typography.eyebrow, color: colors['text-secondary'],
            marginBottom: 4,
          }}>课型</label>
          <div style={{ display: 'flex', gap: 4, flexWrap: 'wrap' }}>
            {LESSON_TYPES.map(lt => (
              <button key={lt.value} onClick={() => setLessonType(lt.value)} style={{
                padding: '4px 14px', borderRadius: radius.pill, fontSize: 13,
                border: lessonType === lt.value
                  ? `1.5px solid ${colors.success}`
                  : `1.5px solid ${colors.hairline}`,
                background: lessonType === lt.value ? green.bg3 : colors.canvas,
                color: lessonType === lt.value ? colors.success : colors['text-secondary'],
                fontWeight: lessonType === lt.value ? 600 : 400,
                cursor: 'pointer', transition: 'all 0.15s',
              }}>
                {lt.label}
              </button>
            ))}
          </div>
        </div>
        <div style={{ flex: '0 1 160px' }}>
          <label style={{
            display: 'block', ...typography.eyebrow, color: colors['text-secondary'],
            marginBottom: 4,
          }}>年级</label>
          <select value={grade} onChange={e => setGrade(e.target.value)} style={{
            width: '100%', padding: '6px 10px', border: `1px solid ${colors.hairline}`,
            borderRadius: radius.sm, fontSize: 13, outline: 'none',
            color: colors['text-primary'], background: colors.canvas,
            boxSizing: 'border-box',
          }}>
            <option value="">不限</option>
            <option value="小学">小学</option>
            <option value="初中">初中</option>
            <option value="高中">高中</option>
          </select>
        </div>
      </div>

      {/* 错误提示 */}
      {error && (
        <div style={{
          ...cardStyle, marginBottom: space.sm, padding: space.sm,
          background: '#fef2f2', borderColor: colors.danger + '30',
        }}>
          <div style={{ color: colors.danger, ...typography['body-sm'] }}>{error}</div>
        </div>
      )}

      {/* 加载中 */}
      {loading && (
        <div style={{
          ...cardStyle, textAlign: 'center', padding: space.xxl,
          display: 'flex', flexDirection: 'column', alignItems: 'center', gap: space.sm,
        }}>
          <div style={{
            width: 40, height: 40, borderRadius: '50%',
            border: `3px solid ${colors['surface-soft']}`,
            borderTopColor: colors.success,
            animation: 'spin 0.8s linear infinite',
          }} />
          <style>{`@keyframes spin { to { transform: rotate(360deg) } }`}</style>
          <span style={{ ...typography['body-sm'], color: colors['text-tertiary'] }}>
            AI 正在分析「{topic}」，生成大纲中...
          </span>
        </div>
      )}

      {/* 大纲为空 */}
      {!loading && !hasSections && !error && (
        <div style={{
          ...cardStyle, textAlign: 'center', padding: space.xxl,
          display: 'flex', flexDirection: 'column', alignItems: 'center', gap: space.md,
        }}>
          <IconPpt size={48} color={colors['text-tertiary']} />
          <div>
            <div style={{ ...typography.subhead, color: colors['text-primary'], marginBottom: 4 }}>
              {topic ? `正在为「${topic}」生成大纲` : '缺少 topic 参数'}
            </div>
            <div style={{ ...typography['body-sm'], color: colors['text-tertiary'] }}>
              请在 URL 中指定 ?topic=你的主题
            </div>
          </div>
          {topic && (
            <button onClick={generateOutline} disabled={loading} style={{
              display: 'inline-flex', alignItems: 'center', gap: 6,
              padding: '10px 24px', background: colors.success, color: '#fff',
              border: 'none', borderRadius: radius.pill, fontSize: 14, fontWeight: 500,
              cursor: 'pointer',
            }}>
              <IconRefresh size={14} color="#fff" /> AI 生成大纲
            </button>
          )}
        </div>
      )}

      {/* 可编辑卡片列表 */}
      {hasSections && !loading && (
        <>
          <div style={{
            ...typography.eyebrow, color: colors['text-tertiary'],
            marginBottom: space.sm, letterSpacing: '0.5px',
          }}>
            大纲章节 · {sections.length} 个章节（点击标题/子主题直接编辑）
          </div>

          <div style={{ display: 'flex', flexDirection: 'column', gap: space.sm }}>
            {sections.map((sec, si) => (
              <div key={sec.id} style={{
                ...cardStyle, padding: space.md,
                borderLeft: `4px solid ${colors.success}`,
                transition: 'box-shadow 0.15s',
              }}>
                {/* 章节头部 */}
                <div style={{
                  display: 'flex', alignItems: 'center', gap: XS,
                  marginBottom: XS,
                }}>
                  <span style={{
                    width: 28, height: 28, borderRadius: '50%', flexShrink: 0,
                    display: 'flex', alignItems: 'center', justifyContent: 'center',
                    background: green.bg3, color: colors.success,
                    fontWeight: 700, fontSize: 12,
                  }}>
                    {si + 1}
                  </span>
                  <input
                    value={sec.title}
                    onChange={e => updateSectionTitle(sec.id, e.target.value)}
                    placeholder="章节标题"
                    style={{
                      flex: 1, border: 'none', borderBottom: `2px solid transparent`,
                      padding: '4px 0', fontSize: 15, fontWeight: 600,
                      color: colors['text-primary'], outline: 'none',
                      background: 'transparent', transition: 'border-color 0.15s',
                    }}
                    onFocus={e => e.currentTarget.style.borderBottomColor = colors.success}
                    onBlur={e => e.currentTarget.style.borderBottomColor = 'transparent'}
                  />
                  <button onClick={() => removeSection(sec.id)} title="删除章节" style={{
                    background: 'none', border: 'none', cursor: 'pointer',
                    color: colors['text-tertiary'], fontSize: 16, lineHeight: 1,
                    padding: '0 4px',
                  }}>
                    ×
                  </button>
                </div>

                {/* 子主题列表 */}
                <div style={{ paddingLeft: 36, display: 'flex', flexDirection: 'column', gap: 3 }}>
                  {sec.subtopics.map((st, sti) => (
                    <div key={sti} style={{ display: 'flex', alignItems: 'center', gap: 4 }}>
                      <span style={{ color: colors['text-tertiary'], fontSize: 10, flexShrink: 0 }}>▸</span>
                      <input
                        value={st}
                        onChange={e => updateSubtopic(sec.id, sti, e.target.value)}
                        placeholder={`子主题 ${sti + 1}`}
                        style={{
                          flex: 1, border: 'none', borderBottom: '1px dashed #e5e5e5',
                          padding: '3px 0', fontSize: 13, outline: 'none',
                          background: 'transparent', color: colors['text-secondary'],
                        }}
                        onFocus={e => e.currentTarget.style.borderBottomColor = colors.success + '60'}
                        onBlur={e => e.currentTarget.style.borderBottomColor = '#e5e5e5'}
                      />
                      <span onClick={() => removeSubtopic(sec.id, sti)} title="删除子主题" style={{
                        cursor: 'pointer', color: colors['text-tertiary'], fontSize: 12,
                        lineHeight: 1, padding: '0 2px',
                      }}>
                        ×
                      </span>
                    </div>
                  ))}
                  <button onClick={() => addSubtopic(sec.id)} style={{
                    background: 'none', border: 'none', cursor: 'pointer',
                    color: colors.success, fontSize: 12, fontWeight: 500,
                    padding: '2px 0', textAlign: 'left', marginTop: 2,
                  }}>
                    + 添加子主题
                  </button>
                </div>
              </div>
            ))}
          </div>

          {/* 添加章节按钮 */}
          <button onClick={addSection} style={{
            display: 'block', width: '100%', marginTop: space.sm, padding: space.sm,
            border: `2px dashed ${colors.hairline}`, borderRadius: radius.md,
            background: 'transparent', color: colors.success, fontSize: 14,
            fontWeight: 500, cursor: 'pointer', transition: 'border-color 0.15s',
          }}
            onMouseEnter={e => e.currentTarget.style.borderColor = colors.success}
            onMouseLeave={e => e.currentTarget.style.borderColor = colors.hairline}
          >
            + 添加章节
          </button>
        </>
      )}

      {/* 底部操作栏 */}
      {hasSections && !loading && (
        <div style={{
          display: 'flex', gap: space.sm, marginTop: space.lg,
          justifyContent: 'center', flexWrap: 'wrap',
          borderTop: `1px solid ${colors.hairline}`, paddingTop: space.md,
        }}>
          {/* 重新生成大纲 */}
          <button onClick={generateOutline} disabled={loading} style={{
            display: 'inline-flex', alignItems: 'center', gap: 6,
            padding: '12px 28px', borderRadius: radius.pill,
            border: `1.5px solid ${colors.success}40`,
            background: green.bg3, color: colors.success,
            fontSize: 14, fontWeight: 500, cursor: loading ? 'not-allowed' : 'pointer',
            opacity: loading ? 0.6 : 1, transition: 'all 0.15s',
          }}>
            <IconRefresh size={16} color={colors.success} />
            重新生成大纲
          </button>

          {/* 导出 HTML 课件 */}
          <button onClick={handleExportHtml} disabled={downloading} style={{
            display: 'inline-flex', alignItems: 'center', gap: 6,
            padding: '12px 28px', borderRadius: radius.pill,
            border: 'none', background: colors.success, color: '#fff',
            fontSize: 14, fontWeight: 600, cursor: downloading ? 'not-allowed' : 'pointer',
            opacity: downloading ? 0.7 : 1, transition: 'opacity 0.15s',
          }}>
            {downloading ? (
              <>
                <div style={{
                  width: 16, height: 16, border: '2px solid rgba(255,255,255,0.3)',
                  borderTopColor: '#fff', borderRadius: '50%',
                  animation: 'spin 0.6s linear infinite',
                }} />
                {downloadMsg}
              </>
            ) : (
              <>
                <IconDownload size={16} color="#fff" />
                导出 HTML 课件
              </>
            )}
          </button>
        </div>
      )}
    </div>
  );
}
